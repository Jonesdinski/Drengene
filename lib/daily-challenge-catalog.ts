export function matchingCharacters(task:ChallengeTemplate,characters:ChallengeCharacter[]){
 return characters.filter(c=>c.level>=task.minLevel&&c.level<=task.maxLevel&&(!task.faction||task.faction===c.faction)&&(!task.classes||task.classes.some(k=>k.toLowerCase()===c.class.toLowerCase()))&&(!task.professions||task.professions.every(p=>c.professions.some(n=>n.toLowerCase()===p.toLowerCase()))));
}
export function eligibleTask(task:ChallengeTemplate,characters:ChallengeCharacter[]){return task.requiresCharacter===false||matchingCharacters(task,characters).length>0;}
export function challengeDay(now=new Date()){
 const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Copenhagen',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(now);
 const get=(type:string)=>parts.find(p=>p.type===type)!.value;
 return `${get('year')}-${get('month')}-${get('day')}`;
}
